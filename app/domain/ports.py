"""Contracts consumed by services; implementations live in adapters."""
from datetime import datetime
from typing import Protocol

from app.domain.commands import (
    CreateBookingCommand, CreateMovieCommand, CreateShowtimeCommand,
    CreateUserCommand, UpdateMovieCommand,
)
from app.domain.entities import (
    BookingEntity, MovieEntity, PaymentEntity, SeatHoldEntity,
    SeatHoldSeatEntity, ShowtimeEntity, UserEntity, UserCredentials,
)
from app.domain.unit_of_work import UnitOfWork


class PasswordSecurity(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, password: str, password_hash: str) -> bool: ...


class TokenIssuer(Protocol):
    def issue(self, user_id: int) -> str: ...


class UserRepository(Protocol):
    async def get_credentials_by_email(self, email: str) -> UserCredentials | None: ...
    async def get_by_id(self, user_id: int) -> UserEntity | None: ...
    async def get_by_email(self, email: str) -> UserEntity | None: ...
    async def create(self, command: CreateUserCommand) -> UserEntity: ...


class MovieRepository(Protocol):
    async def get_all(self) -> list[MovieEntity]: ...
    async def get_by_id(self, movie_id: int) -> MovieEntity | None: ...
    async def create(self, command: CreateMovieCommand) -> MovieEntity: ...
    async def update(self, movie_id: int, command: UpdateMovieCommand) -> MovieEntity | None: ...
    async def delete(self, movie_id: int) -> bool: ...


class ShowtimeRepository(Protocol):
    async def get_by_id_for_update(self, showtime_id: int) -> ShowtimeEntity | None: ...
    async def get_all(self, movie_id: int | None = None) -> list[ShowtimeEntity]: ...
    async def get_by_id(self, showtime_id: int) -> ShowtimeEntity | None: ...
    async def create(self, command: CreateShowtimeCommand) -> ShowtimeEntity: ...


class BookingRepository(Protocol):
    async def get_by_id(self, booking_id: int) -> BookingEntity | None: ...
    async def get_by_ids(self, booking_ids: list[int]) -> list[BookingEntity]: ...
    async def get_by_user_id(self, user_id: int) -> list[BookingEntity]: ...
    async def get_active_seat_numbers(self, showtime_id: int) -> set[str]: ...
    async def update_status(self, booking_id: int, status: str) -> BookingEntity | None: ...
    async def create_many(self, booking_data: list[CreateBookingCommand], user_id: int) -> list[BookingEntity]: ...


class SeatHoldRepository(Protocol):
    async def get_by_id_fresh(self, hold_id: int) -> SeatHoldEntity | None: ...
    async def get_by_id(self, hold_id: int) -> SeatHoldEntity | None: ...
    async def get_active_seat_numbers(self, showtime_id: int, now: datetime) -> set[str]: ...
    async def get_seats(self, hold_id: int) -> list[SeatHoldSeatEntity]: ...
    async def create(self, *, hold_id: int, user_id: int, showtime_id: int,
                     seat_numbers: tuple[str, ...], created_at: datetime,
                     expires_at: datetime) -> SeatHoldEntity: ...
    async def mark_status(self, hold_id: int, status: str) -> SeatHoldEntity: ...
    async def attach_bookings(self, seats: list[SeatHoldSeatEntity], bookings: list[BookingEntity]) -> None: ...


class PaymentRepository(Protocol):
    async def get_by_hold_id(self, hold_id: int) -> PaymentEntity | None: ...
    async def get_by_user_id(self, user_id: int) -> list[PaymentEntity]: ...
    async def create_succeeded(self, *, hold_id: int, user_id: int,
                               amount: int, paid_at: datetime) -> PaymentEntity: ...
